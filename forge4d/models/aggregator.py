    def forward(
        self,
        images: torch.Tensor,
    ) -> Tuple[List[torch.Tensor], int]:
        """
        Args:
            images (torch.Tensor): Input images with shape [B, S, 3, H, W], in range [0, 1].
                B: batch size, S: sequence length, 3: RGB channels, H: height, W: width

        Returns:
            (list[torch.Tensor], int):
                The list of outputs from the attention blocks,
                and the patch_start_idx indicating where patch tokens begin.
        """
        B, T, V, C_in, H, W = images.shape

        if C_in != 3:
            raise ValueError(f"Expected 3 input channels, got {C_in}")

        # Normalize images and reshape for patch embed
        images = (images - self._resnet_mean) / self._resnet_std

        # Reshape to [B*S, C, H, W] for patch embedding
        images = images.view(B * T * V, C_in, H, W)
        
        with torch.no_grad():
            patch_tokens = self.patch_embed(images)

        if isinstance(patch_tokens, dict):
            patch_tokens = patch_tokens["x_norm_patchtokens"]

        _, P, C = patch_tokens.shape

        # Expand camera and register tokens to match batch size and sequence length
        camera_token = slice_expand_and_flatten(self.camera_token, B * T, V)
        register_token = slice_expand_and_flatten(self.register_token, B * T, V)

        # Concatenate special tokens with patch tokens
        tokens = torch.cat([camera_token, register_token, patch_tokens], dim=1)

        pos = None
        if self.rope is not None:
            pos = self.position_getter(B * T * V, H // self.patch_size, W // self.patch_size, device=images.device)

        if self.patch_start_idx > 0:
            # do not use position embedding for special tokens (camera and register tokens)
            # so set pos to 0 for the special tokens
            pos = pos + 1
            pos_special = torch.zeros(B * T * V, self.patch_start_idx, 2).to(images.device).to(pos.dtype)
            pos = torch.cat([pos_special, pos], dim=1)

        # update P because we added special tokens
        _, P, C = tokens.shape

        frame_idx = 0
        global_idx = 0
        temporal_idx = 0
        output_list = []

        for _ in range(self.aa_block_num):
            for attn_type in self.aa_order:
                if attn_type == "frame":
                    tokens, frame_idx, frame_intermediates = self._process_frame_attention(
                        tokens, B, T, V, P, C, frame_idx, pos=pos
                    )
                elif attn_type == "global":
                    tokens, global_idx, global_intermediates = self._process_global_attention(
                        tokens, B, T, V, P, C, global_idx, pos=pos
                    )
                elif attn_type == "temporal":
                    # pass
                    tokens, temporal_idx, temporal_intermediates = self._process_temporal_attention(
                        tokens, B, T, V, P, C, temporal_idx, pos=pos
                    )
                else:
                    raise ValueError(f"Unknown attention type: {attn_type}")

            for i in range(len(frame_intermediates)):
                # concat frame and global intermediates, [B x V x P x 2C]
                concat_inter = torch.cat([frame_intermediates[i], global_intermediates[i]], dim=-1)
                output_list.append(concat_inter)

        del concat_inter
        del frame_intermediates
        del global_intermediates
        return output_list, self.patch_start_idx

    def _process_frame_attention(self, tokens, B, T, V, P, C, frame_idx, pos=None):
        """
        Process frame attention blocks. We keep tokens in shape (B*S, P, C).
        """
        # If needed, reshape tokens or positions:
        if tokens.shape != (B * T * V, P, C):
            tokens = tokens.view(B, T, V, P, C).reshape(B * T * V, P, C)

        if pos is not None and pos.shape != (B * T * V, P, 2):
            pos = pos.view(B, T, V, P, 2).view(B * T * V, P, 2)

        intermediates = []

        # by default, self.aa_block_size=1, which processes one block at a time
        for _ in range(self.aa_block_size):
            tokens = self.frame_blocks[frame_idx](tokens, pos=pos)
            frame_idx += 1
            intermediates.append(tokens.view(B * T, V, P, C))

        return tokens, frame_idx, intermediates

    def _process_global_attention(self, tokens, B, T, V, P, C, global_idx, pos=None):
        """
        Process global attention blocks. We keep tokens in shape (B, S*P, C).
        """
        if tokens.shape != (B * T, V * P, C):
            tokens = tokens.view(B, T, V, P, C).view(B * T, V * P, C)

        if pos is not None and pos.shape != (B * T, V * P, 2):
            pos = pos.view(B, T, V, P, 2).view(B * T, V * P, 2)

        intermediates = []

        # by default, self.aa_block_size=1, which processes one block at a time
        for _ in range(self.aa_block_size):
            tokens = self.global_blocks[global_idx](tokens, pos=pos)
            global_idx += 1
            intermediates.append(tokens.view(B * T, V, P, C))

        return tokens, global_idx, intermediates

    def _process_temporal_attention(self, tokens, B, T, V, P, C, temporal_idx, pos=None):
        """
        Process global attention blocks. We keep tokens in shape (B, S*P, C).
        """
        if tokens.shape != (B * V * P, T, C):
            tokens = tokens.view(B, T, V, P, C).permute(0, 2, 3, 1, 4).reshape(B * V * P, T, C)

        if pos is not None and pos.shape != (B * T, V * P, 2):
            pos = pos.view(B, T, V, P, 2).permute(0, 2, 3, 1, 4).reshape(B * V * P, T, 2)

        intermediates = []

        # by default, self.aa_block_size=1, which processes one block at a time
        for _ in range(self.aa_block_size):
            tokens = self.temporal_blocks[temporal_idx](tokens, pos=pos)
            temporal_idx += 1
            intermediates.append(tokens.view(B, V, P, T, C).permute(0, 3, 1, 2, 4).reshape(B * T, V, P, C))
        
        tokens = tokens.view(B, V, P, T, C).permute(0, 3, 1, 2, 4).reshape(B * T * V, P, C)

        return tokens, temporal_idx, intermediates


